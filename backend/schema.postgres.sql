-- ReMind by Her: sign-ups (PostgreSQL). Safe to run more than once.
-- Twin of schema.sqlite.sql; columns and rules match 1:1. Needs a UTF8 database
-- (the age ranges use an en dash, e.g. '40–44').

CREATE TABLE IF NOT EXISTS registrations (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(60)  NOT NULL CHECK (char_length(full_name) BETWEEN 2 AND 60),
    whatsapp_normalized VARCHAR(13)  NOT NULL UNIQUE CHECK (whatsapp_normalized ~ '^\+91[6-9][0-9]{9}$'),
    email               VARCHAR(120),
    age_range           VARCHAR(20)  NOT NULL CHECK (age_range IN ('Under 40', '40–44', '45–49', '50–54', '55–59', '60+')),
    city                VARCHAR(60)  NOT NULL CHECK (char_length(city) BETWEEN 2 AND 60),
    preferred_language  VARCHAR(30)  CHECK (preferred_language IS NULL OR preferred_language IN ('English', 'Hindi', 'Kannada', 'Other')),
    heard_from          VARCHAR(40),
    consent_community   BOOLEAN      NOT NULL CHECK (consent_community),
    consent_text        TEXT         NOT NULL,
    utm_source          VARCHAR(200),
    utm_medium          VARCHAR(200),
    utm_campaign        VARCHAR(200),
    utm_term            VARCHAR(200),
    utm_content         VARCHAR(200),
    page_url            TEXT,
    consultation_status VARCHAR(30)  NOT NULL DEFAULT 'PENDING_WHATSAPP',
    submitted_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_registrations_status       ON registrations (consultation_status);
CREATE INDEX IF NOT EXISTS idx_registrations_submitted_at ON registrations (submitted_at);
